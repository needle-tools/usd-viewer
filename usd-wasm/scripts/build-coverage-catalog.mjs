import { readFile, writeFile, access, readdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const fixtures = fileURLToPath(new URL('../tests/fixtures/', import.meta.url));
const entries = [];
const suites = (await readdir(path.join(fixtures, 'coverage'), { withFileTypes: true }))
    .filter(entry => entry.isDirectory()).map(entry => entry.name).sort();
for (const suite of suites) {
    const manifest = JSON.parse(await readFile(path.join(fixtures, 'coverage', suite, 'manifest.json'), 'utf8'));
    for (const entry of manifest) {
        if (entries.some(previous => previous.id === entry.id || previous.root === entry.root)) {
            throw new Error(`Duplicate coverage fixture: ${entry.id}`);
        }
        if (!entry.features?.length || !Object.keys(entry.assertions || {}).length || !entry.files?.includes(entry.root)) {
            throw new Error(`Incomplete coverage fixture: ${entry.id}`);
        }
        for (const file of entry.files) await access(path.join(fixtures, file));
        // Detailed native assertions stay in the suite manifests; the viewer
        // only needs the catalog fields and dependency list.
        const { assertions, ...catalogEntry } = entry;
        entries.push({ ...catalogEntry, thumbnail: `thumbnails/${entry.id}.png` });
    }
}
if (entries.length < 100) throw new Error(`Expected at least 100 additional fixtures, found ${entries.length}`);
await writeFile(path.join(fixtures, 'coverage', 'asset-library.js'),
    '// Generated by scripts/build-coverage-catalog.mjs from the three suite manifests.\n' +
    `export const coverageAssetLibrary = ${JSON.stringify(entries, null, 2)};\n`);
console.log(`Catalog: ${entries.length} additional fixtures, ${new Set(entries.flatMap(entry => entry.features)).size} feature tags`);
